// Extracts DISABLED_PAGE from upstream app/c/[token]/route.js so the spike's body matches byte for byte.
import { readFileSync, writeFileSync } from "node:fs";
const src = readFileSync(new URL("../../app/c/[token]/route.js", import.meta.url), "utf8");
const m = src.match(/const DISABLED_PAGE = `([\s\S]*?)`;/);
if (!m) throw new Error("DISABLED_PAGE not found");
writeFileSync(new URL("./src/pages.ts", import.meta.url), `// Generated by gen-pages.mjs from app/c/[token]/route.js. Do not edit.\nexport const DISABLED_PAGE: string = ${JSON.stringify(m[1])};\n`);
